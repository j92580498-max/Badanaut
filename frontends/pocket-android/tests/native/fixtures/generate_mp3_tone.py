"""Regenerate the original 100 ms stereo MP3 test tone (requires libmp3lame).

The fixture is synthesized here; it contains no game audio or recordings.
The encoder is only needed to regenerate the header, never to build/run tests.
"""
import ctypes as C
import ctypes.util
import math
from pathlib import Path

lame = C.CDLL(ctypes.util.find_library("mp3lame"))
lame.lame_init.restype = C.c_void_p
lame.lame_close.argtypes = [C.c_void_p]
for name in ("lame_set_in_samplerate", "lame_set_out_samplerate",
             "lame_set_num_channels", "lame_set_brate", "lame_set_quality"):
    getattr(lame, name).argtypes = [C.c_void_p, C.c_int]
lame.lame_init_params.argtypes = [C.c_void_p]
lame.lame_encode_buffer_interleaved.argtypes = [
    C.c_void_p, C.POINTER(C.c_short), C.c_int, C.POINTER(C.c_ubyte), C.c_int]
lame.lame_encode_flush.argtypes = [C.c_void_p, C.POINTER(C.c_ubyte), C.c_int]
lame.lame_get_lametag_frame.argtypes = [C.c_void_p, C.POINTER(C.c_ubyte), C.c_size_t]
lame.lame_get_lametag_frame.restype = C.c_size_t

encoder = lame.lame_init()
if not encoder:
    raise RuntimeError("lame_init failed")
try:
    for name, value in (("lame_set_in_samplerate", 44100), ("lame_set_out_samplerate", 44100),
                        ("lame_set_num_channels", 2), ("lame_set_brate", 128), ("lame_set_quality", 2)):
        if getattr(lame, name)(encoder, value) < 0:
            raise RuntimeError(name)
    if lame.lame_init_params(encoder) < 0:
        raise RuntimeError("lame_init_params failed")
    samples = (C.c_short * (4410 * 2))()
    for frame in range(4410):
        samples[frame * 2] = round(9000 * math.sin(2 * math.pi * 440 * frame / 44100))
        samples[frame * 2 + 1] = round(6000 * math.sin(2 * math.pi * 880 * frame / 44100))
    output = (C.c_ubyte * 16384)()
    size = lame.lame_encode_buffer_interleaved(encoder, samples, 4410, output, len(output))
    if size < 0:
        raise RuntimeError("MP3 encoding failed")
    encoded = bytearray(output[:size])
    size = lame.lame_encode_flush(encoder, output, len(output))
    if size < 0:
        raise RuntimeError("MP3 flush failed")
    encoded.extend(output[:size])
    size = lame.lame_get_lametag_frame(encoder, output, len(output))
    if not size or size > len(encoded):
        raise RuntimeError("LAME gapless header missing")
    encoded[:size] = output[:size]
finally:
    lame.lame_close(encoder)

lines = ["#pragma once", "#include <cstdint>", "",
         "// Original 100 ms, 44.1 kHz stereo sine tone, generated by generate_mp3_tone.py.",
         "// Left: 440 Hz at 9000; right: 880 Hz at 6000. Includes LAME delay/padding metadata.",
         "inline constexpr uint8_t mp3_tone[] = {"]
for start in range(0, len(encoded), 16):
    lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in encoded[start:start + 16]) + ",")
lines.append("};")
Path(__file__).with_name("mp3_tone.h").write_text("\n".join(lines) + "\n")
print(f"Generated {len(encoded)} bytes of synthesized MP3 test data")
